-- Every design's likes and passes (a vote below zero is a pass), counted in
-- the database: a plain select would stop at the API's row limit.
create or replace function public.hsd_vote_tally()
returns table (design_id text, up bigint, down bigint)
language sql stable security definer set search_path = public as $$
  select v.design_id,
         count(*) filter (where coalesce(v.dir, 1) >= 0),
         count(*) filter (where v.dir < 0)
    from hsd_votes v group by v.design_id;
$$;

-- One vote: 'ok', or 'limit' when p_limit other voters have already voted on
-- this design from this address in the last day. Changing a vote, or voting
-- again after taking it back, does not count again.
create or replace function public.hsd_vote_cast(
  p_design text, p_voter text, p_dir integer, p_ip_hash text,
  p_limit integer)
returns text
language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(
    hashtext('hsd_vote_cast:' || p_ip_hash || ':' || p_design));
  delete from hsd_vote_networks n where n.at < now() - interval '1 day';
  if not exists (select 1 from hsd_votes v
                 where v.design_id = p_design and v.voter_token = p_voter)
     and not exists (select 1 from hsd_vote_networks n
                     where n.ip_hash = p_ip_hash and n.design_id = p_design
                       and n.voter_token = p_voter) then
    if (select count(*) from hsd_vote_networks n
        where n.ip_hash = p_ip_hash and n.design_id = p_design) >= p_limit then
      return 'limit';
    end if;
    insert into hsd_vote_networks (ip_hash, design_id, voter_token)
      values (p_ip_hash, p_design, p_voter);
  end if;
  insert into hsd_votes (design_id, voter_token, dir, updated_at)
    values (p_design, p_voter, case when p_dir < 0 then -1 else 1 end, now())
    on conflict (design_id, voter_token)
    do update set dir = excluded.dir, updated_at = now();
  return 'ok';
end $$;

-- A new voter id (made and signed by the function): {"verdict": "ok" or
-- "limit", "carried": n}. At most p_limit new ids per address per day. A
-- Shopify-era id (p_carry, "v" and 10 to 20 lower-case letters and digits)
-- with votes, never exchanged before, hands its votes to the new id, once.
create or replace function public.hsd_vote_register(
  p_ip_hash text, p_limit integer, p_voter text, p_carry text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  moved integer := 0;
begin
  perform pg_advisory_xact_lock(hashtext('hsd_vote_register:' || p_ip_hash));
  delete from hsd_vote_registrations r where r.at < now() - interval '1 day';
  if (select count(*) from hsd_vote_registrations r
      where r.ip_hash = p_ip_hash) >= p_limit then
    return jsonb_build_object('verdict', 'limit', 'carried', 0);
  end if;
  insert into hsd_vote_registrations (ip_hash) values (p_ip_hash);
  if coalesce(p_carry, '') ~ '^v[0-9a-z]{10,20}$'
     and not exists (select 1 from hsd_vote_exchanged e
                     where e.old_voter = p_carry)
     and exists (select 1 from hsd_votes v where v.voter_token = p_carry) then
    insert into hsd_vote_exchanged (old_voter) values (p_carry);
    update hsd_votes set voter_token = p_voter where voter_token = p_carry;
    get diagnostics moved = row_count;
  end if;
  return jsonb_build_object('verdict', 'ok', 'carried', moved);
end $$;

-- The cull, only when the operator asks (admin_cull): a design with at least
-- p_min votes and under p_ratio likes gets a retire record, unless it is
-- retired now, or was restored (unretired, or a removed design put back)
-- since its last vote, or is a sent-in design not in the vote (waiting or
-- removed). Returns the designs retired.
create or replace function public.hsd_vote_cull(p_min integer, p_ratio numeric)
returns setof text
language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(hashtext('hsd_vote_cull'));
  return query
  with t as (
    select v.design_id,
           count(*) filter (where coalesce(v.dir, 1) >= 0) as up,
           count(*) filter (where v.dir < 0) as down,
           max(v.updated_at) as last_vote
      from hsd_votes v group by v.design_id
  )
  insert into hsd_retired (design_id, retired_at, reason)
    select t.design_id, now(), format('cull: %s up, %s down', t.up, t.down)
      from t
      where t.up + t.down >= p_min
        and t.up::numeric / (t.up + t.down) < p_ratio
        and not exists (select 1 from hsd_retired r
                        where r.design_id = t.design_id
                          and (r.restored_at is null
                               or r.restored_at > t.last_vote))
        and not exists (select 1 from hsd_submissions s
                        where 'sub-' || s.id::text = t.design_id
                          and (s.status <> 'approved'
                               or s.restored_at > t.last_vote))
    returning hsd_retired.design_id;
end $$;

