-- src/vote/functions/vote-api/index.ts (issue #100). Dan runs this once in
-- the Supabase project "Hickory Sands District AVA" (ref
-- yayebhncbagmebwgmezd): SQL Editor > New query > paste > Run
-- (src/vote/SETUP.md), just before he deploys the new function. Running it
-- again changes nothing that is already there.
--
-- It makes or changes only objects named hsd_* that are vote-api's (never the
-- vineyard form's hsd_vineyard_*), and it deletes no vote, design, file or
-- retire record:
--   hsd_votes        + updated_at (when the vote was last cast or changed);
--   hsd_retired      a dated record per retirement, never deleted: + id (the
--                    key, in place of design_id), retired_at, reason,
--                    restored_at; a design is retired while it has a record
--                    with no restored_at. Rows from before get retired_at =
--                    now and reason 'cull (before records)';
--   hsd_submissions  removing is a status: 'removed', + removed_at,
--                    removed_by, status_before, restored_at; + ip_hash (an
--                    HMAC of the sender's address with VOTE_IP_SALT; the raw
--                    ip column is no longer written); and the senders' names
--                    are blanked (Dan, 2026-10-19: names are never kept or
--                    shown);
--   hsd_vote_networks       which voter voted on which design from which
--                           address (an HMAC), for the limit of voters per
--                           design per address per day; rows go after a day;
--   hsd_vote_registrations  new voter ids per address (an HMAC), for the
--                           limit of new ids per address per day; rows go
--                           after a day;
--   hsd_vote_exchanged      Shopify-era voter ids already exchanged for a
--                           signed one (once each);
--   hsd_vote_tally(), hsd_vote_cast(), hsd_vote_register(), hsd_vote_cull():
--                    the counts, a vote, a new voter id and the cull, each
--                    one transaction (the last three under a lock), so
--                    parallel requests cannot slip past a limit.
-- Row level security is on (and forced) with no policies, and every grant to
-- the public (anon) and signed-in (authenticated) roles is revoked: only the
-- function, with the service role, reads or writes.

-- The tables as vote-api made them, for a project that has none yet.
create table if not exists public.hsd_votes (
  design_id    text not null,
  voter_token  text not null,
  dir          integer not null default 1,
  primary key (design_id, voter_token)
);
create table if not exists public.hsd_submissions (
  id            uuid primary key default gen_random_uuid(),
  name          text not null default '',
  title         text not null default '',
  storage_path  text not null,
  content_type  text not null,
  status        text not null default 'pending',
  ip            text,
  created_at    timestamptz not null default now()
);
create table if not exists public.hsd_retired (
  design_id  text primary key
);

-- hsd_votes: when each vote was last cast (for the cull's restored rule).
alter table public.hsd_votes
  add column if not exists updated_at timestamptz not null default now();

-- hsd_retired: dated records, keyed by their own id.
alter table public.hsd_retired
  add column if not exists id bigint generated by default as identity;
alter table public.hsd_retired
  add column if not exists retired_at timestamptz not null default now();
alter table public.hsd_retired add column if not exists reason text;
alter table public.hsd_retired add column if not exists restored_at timestamptz;
update public.hsd_retired set reason = 'cull (before records)'
  where reason is null;
do $$
declare
  key_name text;
  key_cols text[];
begin
  select c.conname, array_agg(a.attname::text order by a.attname)
    into key_name, key_cols
    from pg_constraint c
    join pg_attribute a
      on a.attrelid = c.conrelid and a.attnum = any (c.conkey)
    where c.conrelid = 'public.hsd_retired'::regclass and c.contype = 'p'
    group by c.conname;
  if key_cols is distinct from array['id'] then
    -- the old key, design_id, allowed one record per design: swap it for id
    -- (a constraint, not data: every row stays)
    if key_name is not null then
      execute format('alter table public.hsd_retired drop constraint %I',
                     key_name);
    end if;
    alter table public.hsd_retired add constraint hsd_retired_pkey
      primary key (id);
  end if;
end $$;
create index if not exists hsd_retired_design
  on public.hsd_retired (design_id, restored_at);

-- hsd_submissions: 'removed' as a status, never a deletion; no names.
alter table public.hsd_submissions add column if not exists removed_at timestamptz;
alter table public.hsd_submissions add column if not exists removed_by text;
alter table public.hsd_submissions add column if not exists status_before text;
alter table public.hsd_submissions add column if not exists restored_at timestamptz;
alter table public.hsd_submissions add column if not exists ip_hash text;
do $$
declare
  check_name text;
begin
  for check_name in
    select c.conname from pg_constraint c
      where c.conrelid = 'public.hsd_submissions'::regclass
        and c.contype = 'c'
        and pg_get_constraintdef(c.oid) like '%status%'
        and c.conname <> 'hsd_submissions_status_known'
  loop
    -- an older check that did not allow 'removed' (a constraint, not data)
    execute format('alter table public.hsd_submissions drop constraint %I',
                   check_name);
  end loop;
  if not exists (select 1 from pg_constraint c
                 where c.conrelid = 'public.hsd_submissions'::regclass
                   and c.conname = 'hsd_submissions_status_known') then
    alter table public.hsd_submissions add constraint
      hsd_submissions_status_known
      check (status in ('pending', 'approved', 'removed'));
  end if;
end $$;
update public.hsd_submissions set name = '' where name is distinct from '';
create index if not exists hsd_submissions_uploads
  on public.hsd_submissions (ip_hash, created_at);

